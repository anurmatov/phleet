#!/bin/bash
# Install the pinned Pi CLI (#386) into <dir>, with every @earendil-works/* package held at <version>.
#
#   scripts/install-pi.sh <version> <dir>
#
# The agent image (Dockerfile) and the CI `pi` job both call this, so the Pi that CI tests is the
# Pi the image ships. The binary is <dir>/node_modules/.bin/pi.
#
# WHY NOT `npm install -g @earendil-works/pi-coding-agent@<version>`. Pi declares its sibling
# packages as `^<version>` (coding-agent/package.json), so a plain install resolves them to the
# newest release in that major: on 2026-10-13, `npm install -g …@1.0.4` installed pi-coding-agent
# 1.0.4 on pi-ai, pi-agent-core, pi-tui, pi-mcp, pi-codemode, pi-telemetry and chord 1.2.0. That is
# a Pi nobody tested. A global install has no root package.json, so npm `overrides` cannot apply to
# it; this installs into a project directory whose package.json carries them instead.
#
# The list below is every @earendil-works/* package Pi 1.0.4 installs. If a Pi bump adds one,
# scripts/check-pi-pin.sh fails the build and names it; add it here.
set -euo pipefail

if [ "$#" -ne 2 ]; then
    echo "usage: $0 <version> <dir>" >&2
    exit 2
fi
version=$1
dir=$2

if ! [[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    echo "ERROR: Pi version '$version' is not an exact x.y.z version." >&2
    exit 1
fi

PI_SIBLINGS=(chord pi-agent-core pi-ai pi-codemode pi-mcp pi-telemetry pi-tui)

mkdir -p "$dir"
node - "$version" "${PI_SIBLINGS[@]}" > "$dir/package.json" <<'JS'
const [version, ...siblings] = process.argv.slice(2);
const overrides = Object.fromEntries(siblings.map((name) => [`@earendil-works/${name}`, version]));
process.stdout.write(JSON.stringify({
  private: true,
  description: "Pinned Pi CLI for Fleet (#386); generated by scripts/install-pi.sh",
  dependencies: { "@earendil-works/pi-coding-agent": version },
  overrides,
}, null, 2) + "\n");
JS

npm install --prefix "$dir" --omit=dev --no-audit --no-fund --loglevel=error
test -x "$dir/node_modules/.bin/pi" || { echo "ERROR: $dir/node_modules/.bin/pi was not installed." >&2; exit 1; }
echo "Installed Pi ${version} in ${dir}"
